#!/usr/bin/env python3
"""Write a C++ include holding files as byte arrays, for pictures the port draws itself.

    embed_png.py <out.inc> <name>=<file> [<name>=<file> ...]
"""

import sys
from pathlib import Path


def main() -> None:
    out = Path(sys.argv[1])
    lines = [f"// Generated by scripts/port/embed_png.py from {', '.join(a.split('=', 1)[1] for a in sys.argv[2:])}."]
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = Path(path).read_bytes()
        lines.append(f"constexpr unsigned char {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
        lines.append("};")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
