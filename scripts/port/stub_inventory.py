#!/usr/bin/env python3
"""Regenerate native abort-stub source counts, optionally including linked callers."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "docs/port/stubs.md")
    parser.add_argument("--binary", type=Path)
    parser.add_argument("--objdump", default="objdump")
    args = parser.parse_args()
    rows = []
    totals = []
    for base in ("port/src", "tools/kazarov/src/cpp/sce"):
        total = 0
        for path in sorted((ROOT / base).rglob("*.cpp")):
            if "tests" in path.parts:
                continue
            count = len(re.findall(r"\bPS2_UNIMPLEMENTED\s*\(\s*\)", path.read_text()))
            if count:
                rows.append(f"| `{path.relative_to(ROOT).as_posix()}` | {count} |")
                total += count
        totals.append(f"- `{base}`: {total} abort-stub bodies.")
    lines = ["# Native abort-stub inventory", "", "Generated by `scripts/port/stub_inventory.py`.", "",
             "Source counts include unreachable functions. They count explicit `PS2_UNIMPLEMENTED()` bodies,",
             "rather than empty implementations or successful host substitutes.", "", *totals, "",
             "| Source | Abort-stub bodies |", "|---|---:|", *rows, ""]
    if args.binary:
        process = subprocess.Popen([args.objdump, "-d", "--demangle", str(args.binary)],
                                   stdout=subprocess.PIPE, text=True)
        function = ""
        callers = set()
        for line in process.stdout:
            match = re.match(r"^[0-9a-fA-F]+ <(.*)>:", line)
            if match:
                function = match[1]
            if re.search(r"\b(?:callq?|jmp)\b.*<Ps2Unimplemented", line):
                callers.add(function)
        if process.wait() != 0:
            raise SystemExit("objdump failed")
        lines += ["## Linked executable", "", f"{len(callers)} direct call or tail-call caller functions:", "",
                  *[f"- `{name}`" for name in sorted(callers)], ""]
    lines += ["Regenerate source counts with:", "", "```sh",
              "python scripts/port/stub_inventory.py", "```", "",
              "Add `--binary <executable> --objdump <objdump>` to include the linked inventory.", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
