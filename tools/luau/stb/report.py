"""Renders the corpus survey as Markdown."""

from __future__ import annotations

import collections

from .corpus import Kind
from .scan import ScriptFacts

SEMANTIC_COUNTERS = [
    ("int_div", "Integer divisions (C truncation toward zero; Luau `//` floors)"),
    ("int_mod", "Integer remainders (C sign of dividend; Luau `%` floors)"),
    ("int_mul", "Integer multiplications (32-bit wraparound)"),
    ("int_add", "Integer additions (32-bit wraparound)"),
    ("int_sub", "Integer subtractions (32-bit wraparound)"),
    ("bit_and", "Bitwise and"),
    ("bit_or", "Bitwise or"),
    ("short_circuit", "Short-circuit `&&`/`||` jumps"),
    ("mixed_compare", "Comparisons of an integer with a float"),
    ("float_condition", "Conditions on a float value (always true in the VM)"),
    ("string_condition", "Conditions on a string value (always true in the VM)"),
    ("string_compare", "Comparisons involving a string"),
    ("untyped_arithmetic", "Arithmetic whose operand types were not inferred"),
    ("float_operand_to_int_only_op", "Floats reaching an integer-only operator (runtime error in the VM)"),
    ("store_through_pointer", "Stores through a by-reference array"),
    ("constant_division_by_zero", "Divisions by a constant zero"),
]


def _table(headers: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines + [""]


def render(facts: list[ScriptFacts], catalog: dict, findings: dict, source: str) -> str:
    """The Markdown corpus report."""
    by_kind = {kind: [f for f in facts if f.kind == kind] for kind in Kind}
    out = [
        "# Script corpus survey",
        "",
        f"Generated by `tools/luau/survey.py` from `{source}`. Do not edit by hand.",
        "",
        "## Scripts by kind",
        "",
    ]
    rows = []
    all_bodies = collections.Counter()
    for kind, scripts in by_kind.items():
        bodies = collections.Counter()
        for script in scripts:
            bodies.update(script.bodies)
        all_bodies.update(bodies)
        commands = {c for s in scripts for c, _ in s.ext_sites if c is not None}
        registered = len(catalog["kinds"][kind.value]["commands"])
        rows.append([
            kind.value,
            len(scripts),
            sum(s.magic == "SB2" for s in scripts),
            sum(s.global_num > 0 for s in scripts),
            sum(s.functions for s in scripts),
            sum(s.functions - s.referenced for s in scripts),
            len(bodies),
            sum(len(s.programs) for s in scripts),
            max((s.max_local for s in scripts), default=0),
            max((s.max_arg for s in scripts), default=0),
            sum(len(s.ext_sites) for s in scripts),
            f"{len(commands)} / {registered}",
            sum(s.opcodes["WAIT"] for s in scripts),
            sum(s.opcodes["SKIP_END"] for s in scripts),
            sum(s.opcodes["PRINT"] for s in scripts),
        ])
    rows.append(["**all**", len(facts), sum(s.magic == "SB2" for s in facts), sum(s.global_num > 0 for s in facts), sum(s.functions for s in facts),
                 sum(s.functions - s.referenced for s in facts), len(all_bodies), sum(len(s.programs) for s in facts),
                 max(s.max_local for s in facts), max(s.max_arg for s in facts), sum(len(s.ext_sites) for s in facts), "",
                 sum(s.opcodes["WAIT"] for s in facts), sum(s.opcodes["SKIP_END"] for s in facts), sum(s.opcodes["PRINT"] for s in facts)])
    out += _table(["Kind", "Files", "SB2", "With globals", "Functions", "Uncalled helpers", "Unique bodies", "Program entries",
                   "Max locals", "Max args", "EXT sites", "Commands used / registered", "WAIT", "SKIP_END", "PRINT"], rows)
    out += ["Unique bodies are counted by a location-independent hash of the function and the bodies it calls.", ""]

    errors = [f for f in facts if f.error]
    stack_errors = [(f.path, e) for f in facts for e in f.stack_errors]
    irreducible = [(f.path, b) for f in facts for b in f.irreducible]
    out += ["## Decoding and control flow", ""]
    out += [f"- Scripts that fail to decode: {len(errors)}"]
    out += [f"  - `{f.path}`: {f.error}" for f in errors[:20]]
    out += [f"- Functions with inconsistent operand stacks: {len(stack_errors)}"]
    out += [f"  - `{path}` {error}" for path, error in stack_errors[:20]]
    out += [f"- Functions with irreducible control flow: {len(irreducible)}"]
    out += [f"  - `{path}` function at {block:#x}" for path, block in irreducible[:20]]
    out += [f"- Natural loops: {sum(f.loops for f in facts)}", f"- Recursive functions: {sum(f.recursive for f in facts)}", ""]

    out += ["## Program numbers", ""]
    for kind, scripts in by_kind.items():
        numbers = collections.Counter(no for s in scripts for no in s.programs)
        if numbers:
            listing = ", ".join(f"{no} ({n})" for no, n in sorted(numbers.items()))
            out += [f"- **{kind.value}**: {listing}"]
    out += ["", "Each entry is a program number followed by the number of files that define it.", ""]

    opcodes = collections.Counter()
    loads, addrs = collections.Counter(), collections.Counter()
    for script in facts:
        opcodes.update(script.opcodes)
        loads.update(script.load_modes)
        addrs.update(script.addr_modes)
    out += ["## Opcodes", ""]
    out += _table(["Opcode", "Count"], [[name, n] for name, n in opcodes.most_common()])
    out += ["## Address modes", ""]
    out += _table(["Mode", "LOAD", "LOAD_ADDR"], [[m, loads[m], addrs[m]] for m in sorted(set(loads) | set(addrs), key=lambda m: -(loads[m] + addrs[m]))])

    counters = collections.Counter()
    for script in facts:
        counters.update(script.counters)
    out += ["## Semantics the translation must preserve", ""]
    out += _table(["Construct", "Sites"], [[label, counters[key]] for key, label in SEMANTIC_COUNTERS])

    out += ["## Strings", ""]
    strings = sum(f.strings for f in facts)
    non_ascii = sum(f.non_ascii_strings for f in facts)
    bad = [(f.path, s) for f in facts for s in f.non_round_trip_strings]
    out += [f"- String pushes: {strings}", f"- Containing CP932 (non-ASCII) bytes: {non_ascii}", f"- Not reproducible through a CP932 → UTF-8 → CP932 round trip: {len(bad)}"]
    out += [f"  - `{path}`: `{text}`" for path, text in bad[:20]]
    out += [""]

    out += ["## Most shared function bodies", ""]
    files_with = collections.Counter()
    for script in facts:
        files_with.update(script.bodies.keys())
    out += _table(["Body hash", "Occurrences", "Files"], [[h[:12], n, files_with[h]] for h, n in all_bodies.most_common(15)])

    out += ["## Command catalog coverage", ""]
    rows = []
    for kind in Kind:
        commands = catalog["kinds"][kind.value]["commands"]
        signatures = [s for c in commands for s in c["signatures"]]
        params = [p for s in signatures for p in s["params"]]
        rows.append([
            kind.value,
            len(commands),
            sum(c["uses"]["sites"] > 0 for c in commands),
            len(signatures),
            sum(len(c["signatures"]) > 1 for c in commands),
            len(params),
            sum(p.get("name_source") == "handler" for p in params),
            sum(p["type"] == "unknown" for p in params),
            sum(bool(s.get("review")) for s in signatures),
            findings["dynamic"][kind.value],
        ])
    out += _table(["Kind", "Registered", "Used", "Signatures", "Arity-polymorphic", "Parameters", "Named from handler", "Unknown type", "Signatures to review", "Non-constant command sites"], rows)
    out += [f"- Calls to unregistered command numbers: {len(findings['unregistered'])}"]
    out += [f"  - {kind} command {no} with {argc} arguments: {sites} sites, e.g. `{files[0]}`" for kind, no, argc, sites, files in findings["unregistered"][:30]]
    out += [f"- Calls with an argument count the handler rejects: {len(findings['rejected'])}"]
    out += [f"  - {kind} `{handler}` with {argc} arguments: {sites} sites" for kind, handler, argc, sites in findings["rejected"][:30]]
    out += [f"- Scripts where at least a tenth of the calls name an unregistered command or an arity the handler rejects: {len(findings['misfit'])}"]
    out += [f"  - `{path}` ({kind}): {bad} of {total} calls" for path, kind, bad, total in findings["misfit"]]
    out += [f"- Command numbers registered twice (the later registration wins): {len(findings['duplicates'])}"]
    out += [f"  - {kind} {no}: `{first}` then `{second}`" for kind, no, first, second in findings["duplicates"]]
    out += [""]
    return "\n".join(out)
