"""Generates the Luau type declarations of the native script API from the command catalog.

Each kind becomes one `declare <namespace>` table with an entry per catalogued argument count, plus an unsuffixed entry
that picks the arity from the number of inputs, as the runtime contract describes. A command with tagged parameters
also has an `Int` and a `Float` variant of its tagged signatures. The shared integer and float aliases
go into `types.d.luau`. Run without arguments to write `port/src/luau/api/`; `--check` writes nothing and fails if the
checked-in files differ from the catalog.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
CATALOG = REPO / "tools" / "luau" / "commands.json"
OUTPUT = REPO / "port" / "src" / "luau" / "api"
HEADER = "-- Generated by tools/luau/stb2luau/api.py from tools/luau/commands.json; do not edit."
ALIASES = ("s8", "u8", "s16", "u16", "s32", "u32", "f32")
# The entry point for a command number the kind does not register, or an arity the catalog does not list.
EXT_NAME = "call_command"
EXT = f"{EXT_NAME}: (no: number, ...any) -> (),"
EXT_DOC = "--- Calls a command number that this kind does not register, or an arity the catalog does not list; it returns nothing."
# A tagged parameter is one whose handler reads its slot's integer or float tag, so each call chooses the type: the
# command's _int and _float variants give every tagged parameter of a signature that type.
VARIANTS = {"s32": "_int", "f32": "_float"}
# An in-out parameter ("inout") is a reference the handler reads and writes: the call passes the value and gets it back.
INPUTS = frozenset({"in", "inout"})
OUTPUTS = frozenset({"out", "inout"})


# How a handler takes a value of the other kind than its parameter type, a string for a number or a number for a string
# (the "other_kind" of a parameter). Retail hands it the slot as it is, and:
#   accepted: the handler branches on the slot's tag and takes either kind;
#   ignored:  the handler does nothing with that kind, so the call is dropped;
#   nonzero:  the handler only tests the number for zero, and a string's address is never zero, so 1 is passed;
#   address:  the handler reads the number as a string's address, 0 being no string and any other naming none the
#             handler finds, so nil or "" is passed.
OTHER_KINDS = frozenset({"accepted", "ignored", "nonzero", "address"})


def other_value(param: dict, value: object) -> object:
    """The value a handler sees for an input of the other kind, under the parameter's other_kind."""
    handling = param.get("other_kind")
    if handling == "nonzero":
        return 1
    if handling == "address":
        return None if value == 0 else ""
    return value


def tagged(signature: dict) -> bool:
    """Whether a signature has a parameter whose integer or float type the call chooses."""
    return any(param.get("tagged") for param in signature["params"])


def variant(signature: dict, type_name: str) -> dict:
    """The signature with every tagged parameter given an integer (`s32`) or float (`f32`) type."""
    params = [{**param, "type": type_name} if param.get("tagged") else param for param in signature["params"]]
    return {**signature, "params": params}


def ignores_reference(signature: dict, args: list, is_reference: Callable[[Any], bool]) -> bool:
    """Whether a call passes a reference as the tagged input of a signature without outputs.

    Such a handler stores its tagged input only when the slot holds an integer or a float, so a reference makes the
    call do nothing.
    """
    if any(param["dir"] != "in" for param in signature["params"]):
        return False
    return any(param.get("tagged") and is_reference(arg) for param, arg in zip(signature["params"], args))


def value_form(signature: dict) -> dict | None:
    """The signature with each output that call sites also pass a value to read as an input, or None when there is none.

    Retail hands such a handler the value itself: one that branches on the slot's tag or reads the slot as an input sees
    the value, and one that only writes an output writes nothing. The form's parameters take the value's observed type.
    """
    params = []
    flipped = False
    for position, param in enumerate(signature["params"], 1):
        observed = param.get("observed", {})
        values = sorted((count, key[3:]) for key, count in observed.items() if key.startswith("in "))
        if param["dir"] == "out" and values:
            params.append({**param, "name": f"arg{position}", "dir": "in", "type": values[-1][1], "tagged": False})
            flipped = True
        else:
            params.append(param)
    if not flipped:
        return None
    return {**signature, "params": params, "values": True}


def site_signature(signature: dict, values: set[int]) -> dict:
    """The signature a call site uses: the value form when the site passes values exactly at the outputs the form reads
    (positions from 1), and the catalogued signature otherwise."""
    form = value_form(signature) if values else None
    if form is None:
        return signature
    read = {
        position
        for position, (param, form_param) in enumerate(zip(signature["params"], form["params"]), 1)
        if param["dir"] != form_param["dir"]
    }
    return form if read == values else signature


def value_forms(command: dict) -> list[dict]:
    """The value forms of a command's signatures, sorted by argument count."""
    forms = (value_form(signature) for signature in sorted(command["signatures"], key=lambda s: s["argc"]))
    return [form for form in forms if form is not None]


def suffix(signature: dict) -> str:
    """The suffix that names one signature: its argument count, followed by `v` for a value form."""
    return f"{signature['argc']}v" if signature.get("values") else str(signature["argc"])


def dispatched_forms(command: dict) -> list[dict]:
    """The value forms the unsuffixed name reaches: those whose input count no catalogued signature takes, and no other
    value form shares. A command with an input of any type has none, as Luau could not tell its overloads apart."""
    signatures = command["signatures"]
    if len(signatures) > 1 and any(p["type"] == "unknown" and p["dir"] != "out" for s in signatures for p in s["params"]):
        return []
    taken = {_ins(signature) for signature in signatures}
    counts: dict[int, int] = {}
    forms = value_forms(command)
    for form in forms:
        counts[_ins(form)] = counts.get(_ins(form), 0) + 1
    return [form for form in forms if _ins(form) not in taken and counts[_ins(form)] == 1]


def _type(name: str) -> str:
    if name in ALIASES or name in ("string", "boolean"):
        return name
    if name == "array":
        return "{number}"
    return "any"


def _param_type(param: dict) -> str:
    """The Luau type of an input, widened for the other kind its handler accepts."""
    text = _type(param["type"])
    if param.get("other_kind") == "accepted":
        return f"{text} | {'number' if param['type'] == 'string' else 'string'}"
    if param.get("other_kind") == "address":
        return f"{text}?"
    return text


def _function(signature: dict) -> str:
    params = signature["params"]
    ins = [f"{param['name']}: {_param_type(param)}" for param in params if param["dir"] in INPUTS]
    # A deferred output is written by the engine later, so the call returns nothing for it.
    outs = [f"{_type(param['type'])}?" for param in params if param["dir"] in OUTPUTS and not param.get("deferred")]
    if not outs:
        returns = "()"
    elif len(outs) == 1:
        returns = outs[0]
    else:
        returns = f"({', '.join(outs)})"
    return f"({', '.join(ins)}) -> {returns}"


def _outs(signature: dict) -> int:
    return sum(param["dir"] in OUTPUTS for param in signature["params"])


def _ins(signature: dict) -> int:
    return sum(param["dir"] in INPUTS for param in signature["params"])


def _unsuffixed(signatures: list[dict]) -> str:
    chosen: dict[int, dict] = {}
    for signature in signatures:
        best = chosen.get(_ins(signature))
        if best is None or _outs(signature) > _outs(best) or (_outs(signature) == _outs(best) and signature["argc"] < best["argc"]):
            chosen[_ins(signature)] = signature
    functions = [_function(chosen[count]) for count in sorted(chosen)]
    if len(functions) == 1:
        return functions[0]
    return " & ".join(f"({function})" for function in functions)


def _namespace(kind: dict) -> str:
    lines = [HEADER, f"declare {kind['namespace']}: {{"]
    for command in sorted(kind["commands"], key=lambda command: command["no"]):
        signatures = sorted(command["signatures"], key=lambda signature: signature["argc"])
        if not signatures:
            continue
        if command.get("description"):
            lines.append(f"\t--- {command['description']}")
        lines.append(f"\t{command['luau']}: {_unsuffixed(signatures + dispatched_forms(command))},")
        for signature in signatures + value_forms(command):
            lines.append(f"\t{command['luau']}_{suffix(signature)}: {_function(signature)},")
        variants = [signature for signature in signatures if tagged(signature)]
        for type_name, variant_suffix in VARIANTS.items() if variants else ():
            name = f"{command['luau']}{variant_suffix}"
            retyped = [variant(signature, type_name) for signature in variants]
            lines.append(f"\t--- {command['luau']} with its value as {'an integer' if type_name == 's32' else 'a float'}.")
            lines.append(f"\t{name}: {_unsuffixed(retyped)},")
            for signature in retyped:
                lines.append(f"\t{name}_{signature['argc']}: {_function(signature)},")
    lines += [f"\t{EXT_DOC}", f"\t{EXT}", "}"]
    return "\n".join(lines) + "\n"


def _types() -> str:
    lines = [HEADER, "-- Integer and float aliases of the script machine's values."]
    lines += [f"export type {alias} = number" for alias in ALIASES]
    lines += [
        "-- The C library's single-precision sine and cosine, as the host links them.",
        "declare cmath: {",
        "\tsinf: (x: number) -> number,",
        "\tcosf: (x: number) -> number,",
        "}",
        "-- Machine state the host owns: whether the running script is skipping, the skip end, and the item the use item menu wrote.",
        "declare vmhost: {",
        "\tskipping: () -> boolean,",
        "\tskip_end: () -> boolean,",
        "\tused_item: () -> number?,",
        "}",
    ]
    return "\n".join(lines) + "\n"


def declarations(catalog: dict) -> dict[str, str]:
    """Declaration file texts keyed by file name: `types.d.luau` and one `<namespace>.d.luau` per kind."""
    files = {"types.d.luau": _types()}
    for kind in catalog["kinds"].values():
        files[f"{kind['namespace']}.d.luau"] = _namespace(kind)
    return files


def write(directory: Path, catalog: dict) -> list[Path]:
    """Writes the declaration files into a directory, with LF newlines, and returns their paths."""
    directory.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in declarations(catalog).items():
        path = directory / name
        path.write_bytes(text.encode("utf-8"))
        paths.append(path)
    return paths


def stale(directory: Path, catalog: dict) -> list[str]:
    """Names of the declaration files that are missing from, or differ in, a directory."""
    differing = []
    for name, text in declarations(catalog).items():
        path = directory / name
        if not path.is_file() or path.read_bytes() != text.encode("utf-8"):
            differing.append(name)
    return differing


def main(argv: list[str] | None = None) -> int:
    """Writes the declarations, or with --check reports stale files and returns 1 when any differ."""
    parser = argparse.ArgumentParser(description="Generate Luau declarations of the native script API.")
    parser.add_argument("--check", action="store_true", help="report stale files without writing and exit 1 if any differ")
    args = parser.parse_args(argv)
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    if args.check:
        differing = stale(OUTPUT, catalog)
        for name in differing:
            print(f"out of date: {OUTPUT / name}", file=sys.stderr)
        return 1 if differing else 0
    for path in write(OUTPUT, catalog):
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
