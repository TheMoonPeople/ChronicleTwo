"""Generate the C++ script-command tables from the Luau command catalog.

Reads tools/luau/commands.json and emits the constexpr tables consumed by
port/src/luau_bindings.hpp for the requested kinds. The output is
deterministic and is only rewritten when its content changes.
"""

from __future__ import annotations

import argparse
import json
import os
import re
from pathlib import Path

IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
PROGRAM_NAME = re.compile(r"^[a-z_][a-z0-9_]*$")
# The script table's setup field is run by run(-1), so no program may take its name.
RESERVED_PROGRAM_NAMES = frozenset({"setup"})

HEADER = "// Generated by tools/luau/bindings.py from tools/luau/commands.json; do not edit."

DIRECTIONS = {"in": "In", "out": "Out", "inout": "InOut"}
TYPES = {
    "s8": "S8",
    "u8": "U8",
    "s16": "S16",
    "u16": "U16",
    "s32": "S32",
    "u32": "U32",
    "f32": "F32",
    "string": "String",
    "boolean": "Boolean",
    "array": "Array",
    "unknown": "Unknown",
}


def _pascal(name: str) -> str:
    """Convert a snake_case kind name to PascalCase."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def _bool(value: bool) -> str:
    """Render a Python bool as a C++ literal."""
    return "true" if value else "false"


def _param(param: dict) -> str:
    """Render one parameter as a Param initializer; a tagged parameter's type is the call's choice."""
    tagged = ", true" if param.get("tagged") else ""
    return f"{{{DIRECTIONS[param['dir']]}, {TYPES[param['type']]}{tagged}}}"


def _validate_kinds(catalog: dict, kinds: list[str]) -> None:
    """Exit with a message unless every requested kind exists exactly once in the catalog."""
    available = catalog["kinds"]
    seen: set[str] = set()
    for name in kinds:
        if name not in available:
            raise SystemExit(f"unknown kind {name!r}; catalog has: {', '.join(sorted(available))}")
        if name in seen:
            raise SystemExit(f"kind {name!r} requested more than once")
        seen.add(name)


def _named_programs(programs: dict | None, kind_name: str) -> list[dict]:
    """Return the kind's named programs sorted by number, exiting unless names and numbers are valid and unique."""
    if programs is None or kind_name not in programs["kinds"]:
        return []
    entries = sorted(programs["kinds"][kind_name]["programs"], key=lambda p: p["no"])
    numbers: set[int] = set()
    names: set[str] = set()
    for entry in entries:
        no = entry["no"]
        name = entry["name"]
        if not PROGRAM_NAME.match(name):
            raise SystemExit(f"{kind_name} program {no} has an invalid name {name!r}")
        if name in RESERVED_PROGRAM_NAMES:
            raise SystemExit(f"{kind_name} program {no} uses the reserved name {name!r}")
        if no in numbers:
            raise SystemExit(f"{kind_name} program number {no} is listed more than once")
        if name in names:
            raise SystemExit(f"{kind_name} program name {name!r} is used more than once")
        numbers.add(no)
        names.add(name)
    return entries


def fallback_modules(fallback: dict | None) -> list[str]:
    """The module keys of the scripts fallback.json keeps on the interpreter, as transpile.py names modules."""
    modules = []
    for path in (fallback or {}).get("scripts", {}):
        if path.endswith(".stb_"):
            modules.append(path[: -len(".stb_")] + "_")
        elif path.endswith(".stb"):
            modules.append(path[: -len(".stb")])
        else:
            raise SystemExit(f"fallback entry {path!r} is not a script path")
    return sorted(set(modules))


def generate(catalog: dict, kinds: list[str], programs: dict | None = None, fallback: dict | None = None) -> str:
    """Return the C++ source for the given kinds, in the order requested.

    programs is the parsed programs.json; kinds it does not name get no program table. fallback is the parsed
    fallback.json, whose scripts the runtime never loads as modules.
    """
    _validate_kinds(catalog, kinds)

    lines = [
        HEADER,
        '#include "luau_bindings.hpp"',
        "",
        "namespace luau_bindings {",
        "namespace {",
        "",
        "using enum Direction;",
        "using enum Type;",
        "",
    ]
    kind_rows: list[str] = []

    for kind_name in kinds:
        kind = catalog["kinds"][kind_name]
        space = kind["namespace"]
        assert IDENTIFIER.match(kind_name), kind_name
        assert IDENTIFIER.match(space), space
        prefix = "k" + _pascal(kind_name)

        lines.append(f"// {kind_name}")
        command_rows: list[str] = []
        for command in sorted(kind["commands"], key=lambda c: c["no"]):
            assert IDENTIFIER.match(command["luau"]), command["luau"]
            no = command["no"]
            signature_rows: list[str] = []
            for signature in sorted(command["signatures"], key=lambda s: s["argc"]):
                argc = signature["argc"]
                if signature["params"]:
                    array = f"{prefix}{no}Argc{argc}"
                    items = ", ".join(_param(p) for p in signature["params"])
                    lines.append(f"constexpr Param {array}[] = {{{items}}};")
                else:
                    array = "{}"
                rejected = _bool(signature.get("handler_rejects", False))
                signature_rows.append(f"{{{argc}, {rejected}, {array}}}")
            lines.append(f"constexpr Signature {prefix}{no}[] = {{{', '.join(signature_rows)}}};")
            command_rows.append(f'    {{"{command["luau"]}", {no}, {prefix}{no}}},')

        named = _named_programs(programs, kind_name)
        if named:
            items = ", ".join(f'{{{entry["no"]}, "{entry["name"]}"}}' for entry in named)
            lines.append(f"constexpr Program {prefix}Programs[] = {{{items}}};")
            program_table = f"{prefix}Programs"
        else:
            program_table = "{}"

        lines.append("")
        lines.append(f"constexpr Command {prefix}Commands[] = {{")
        lines.extend(command_rows)
        lines.append("};")
        lines.append("")
        kind_rows.append(f'    {{"{kind_name}", "{space}", {kind["table_size"]}, {prefix}Commands, {program_table}}},')

    lines.append("constexpr Kind kKinds[] = {")
    lines.extend(kind_rows)
    lines.append("};")
    lines.append("")
    modules = fallback_modules(fallback)
    lines.append("constexpr std::string_view kFallback[] = {")
    lines.extend(f'    "{module}",' for module in modules)
    if not modules:
        lines.append('    "",')
    lines.append("};")
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("std::span<const Kind> Kinds() { return kKinds; }")
    lines.append("")
    lines.append("std::span<const std::string_view> FallbackModules() { return kFallback; }")
    lines.append("")
    lines.append("} // namespace luau_bindings")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Parse arguments, generate the bindings and write them if they changed."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("catalog", type=Path, help="Path to commands.json.")
    parser.add_argument("output", type=Path, help="Path of the generated C++ source.")
    parser.add_argument("--kinds", required=True, help="Comma-separated kind names, in output order.")
    parser.add_argument("--programs", required=True, type=Path, help="Path to programs.json.")
    parser.add_argument("--fallback", type=Path, help="Path to fallback.json.")
    args = parser.parse_args()

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    programs = json.loads(args.programs.read_text(encoding="utf-8"))
    fallback = json.loads(args.fallback.read_text(encoding="utf-8")) if args.fallback else None
    text = generate(catalog, [name.strip() for name in args.kinds.split(",")], programs, fallback)

    try:
        with args.output.open(encoding="utf-8", newline="") as handle:
            if handle.read() == text:
                # Touch the output so timestamp-based builds treat it as up to date.
                os.utime(args.output)
                return
    except FileNotFoundError:
        pass
    with args.output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
