void CMonsterMan::PriorityLevelCheck() {
    int order[MONSTER_ACTIVE_MAX];
    int count = 0;
    int i;
    int j;
    int swapped;

    for (i = 0; i < MONSTER_ACTIVE_MAX; i++) {
        if (active[i] != NULL) {
            active[i]->priority = -1;

            if (active[i]->chara_kind == (int) ACTION_KIND_SCRIPT && active[i]->state != 0) {
                order[count] = i;
                count++;
            }
        }
    }

    for (i = 0; i < count - 1; i++) {
        for (j = i + 1; j < count; j++) {
            if (!(active[order[i]]->target_dist <=
                  active[order[j]]->target_dist)) {
                swapped = order[i];
                order[i] = order[j];
                order[j] = swapped;
            }
        }
    }

    for (i = 0; i < count; i++) {
        active[order[i]]->priority = i;
    }
}

