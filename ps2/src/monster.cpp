int CheckGiftPack(CActiveMonster *monster, CColPrim *prim) {
    int key = monster->tbl->gift_type;
    int row = 0;
    int i;

    while (gift_item_tbl[row][0] != -1) {
        if (gift_item_tbl[row][0] == key) {
            break;
        }

        row++;
    }

    if (gift_item_tbl[row][0] == -1) {
        return 0;
    }

    for (i = 0; i < 3; i++) {
        if (prim->gift[i] != gift_item_tbl[row][1]) {
            return 0;
        }
    }

    return 1;
}

